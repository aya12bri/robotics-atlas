// build-offline.mjs — writes sw.js, the service worker of the offline mode (source: tools/sw-src.js).
//   node tools/build-offline.mjs        (run it last, after every other tool: it records the content of every file)
// sw.js starts with the list of the site's files and a short hash of each one, so a visitor's stored copy of a file is
// replaced exactly when the file changes, and the browser installs a new service worker whenever any file changed.
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const ignore = fs.readFileSync(path.join(root, '.assetsignore'), 'utf8').split('\n').map((s) => s.trim()).filter(Boolean);
const SKIP = new Set([...ignore, 'sw.js', 'sitemap.xml', 'robots.txt', 'og-image.jpg', 'README.md', 'package.json', 'package-lock.json']);
const files = [];
(function walk(dir) {
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    const rel = path.relative(root, path.join(dir, e.name)).split(path.sep).join('/');
    if (e.name.startsWith('.') || SKIP.has(rel) || SKIP.has(e.name)) continue;
    if (e.isDirectory()) walk(path.join(dir, e.name));
    else if (/-fr\.html$/.test(e.name)) continue;          // the French twins: offline, sw.js shows their English page (in French)
    else if (/\.(html|js|css|svg|png|jpg|jpeg|webp|json|webmanifest|woff2?)$/i.test(e.name)) files.push(rel);
  }
})(root);
files.sort();

const FILES = {}, SIZES = {};
let SIZE = 0;
for (const f of files) {
  const buf = fs.readFileSync(path.join(root, f));
  FILES['/' + f] = crypto.createHash('sha1').update(buf).digest('hex').slice(0, 10);
  SIZES['/' + f] = buf.length; SIZE += buf.length;
}
// stored at the first visit: the home page, the offline page and everything the pages share
const CORE = ['/index.html', '/offline.html', '/certificate.html', '/style.css', '/nav.js', '/helpers.js', '/dharm.js', '/lesson-quiz.js',
  '/search.js', '/search-index.js', '/courses.js', '/certificate.js', '/logo.svg', '/manifest.webmanifest',
  '/i18n/fr-common.js', '/i18n/fr-index.js', '/vendor/three.module.min.js', '/vendor/addons/controls/OrbitControls.js']
  .concat(Object.keys(FILES).filter((k) => k.startsWith('/icons/') || k.startsWith('/thumbs/anatomy')));
const missing = CORE.filter((k) => !FILES[k]);
if (missing.length) { console.error('missing core files:', missing); process.exit(1); }
const VERSION = crypto.createHash('sha1').update(JSON.stringify(FILES)).digest('hex').slice(0, 10);

const src = fs.readFileSync(path.join(root, 'tools', 'sw-src.js'), 'utf8');
const out = `// sw.js — generated by tools/build-offline.mjs from tools/sw-src.js: do not edit.\n` +
  `const VERSION = '${VERSION}', SIZE = ${SIZE};\nconst FILES = ${JSON.stringify(FILES)};\nconst SIZES = ${JSON.stringify(SIZES)};\nconst CORE = ${JSON.stringify(CORE)};\n` + src;
fs.writeFileSync(path.join(root, 'sw.js'), out);
const core = CORE.reduce((a, k) => a + SIZES[k], 0);
console.log(`sw.js: ${files.length} files, ${(SIZE / 1048576).toFixed(1)} MB in all, core ${CORE.length} files ${(core / 1048576).toFixed(1)} MB, version ${VERSION}`);
