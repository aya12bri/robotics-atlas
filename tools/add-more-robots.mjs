// add-more-robots.mjs — on the home page, under the 3D gallery: cards of the robot families that have their own page but no
// place in the gallery (cylindrical, spherical, 7-axis, hexapod), with their French texts in i18n/fr-index.js. Idempotent.
//   PLAYWRIGHT=… CHROME=… node tools/add-more-robots.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { REG, reset, tx } from './lib.mjs';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const { chromium } = await import(process.env.PLAYWRIGHT || 'playwright-core');
reset();
// [page, name, kinematics, one simple sentence]
const CARDS = [
  ['cylindrical.html', ['Cylindrical robot', 'Robot cylindrique'], 'R-P-P', ['A column that turns, a carriage that goes up, an arm that comes out.', 'Une colonne qui tourne, un chariot qui monte, un bras qui sort.']],
  ['spherical.html', ['Spherical (polar) robot', 'Robot sphérique (polaire)'], 'R-R-P', ['Two angles and a telescopic arm: the very first industrial robot.', 'Deux angles et un bras télescopique : le tout premier robot industriel.']],
  ['redundant.html', ['7-axis redundant robot', 'Robot redondant 7 axes'], '7 × R', ['One joint too many, on purpose: the elbow moves, the tool stays still.', 'Une articulation de trop, exprès : le coude bouge, l\'outil reste immobile.']],
  ['hexapod.html', ['Hexapod (Stewart platform)', 'Hexapode (plateforme de Stewart)'], '6-UPS', ['Six legs move a platform in 6 directions: flight simulators.', 'Six jambes bougent une plateforme dans 6 directions : simulateurs de vol.']]
];
const t = (x) => tx(x[0], x[1]);
const card = ([h, n, k, d]) => { const img = h.replace('.html', ''); return `<a href="${h}" class="anat-card"><span class="anat-img"><img class="th-light" src="thumbs/robot-${img}.jpg" alt="" width="670" height="500" loading="lazy" decoding="async"><img class="th-dark" src="thumbs/robot-${img}-dark.jpg" alt="" width="670" height="500" loading="lazy" decoding="async"><i>${k}</i></span><b>${t(n)}</b><em>${t(d)}</em><span class="anat-go">${tx('Open the 3D model →', 'Ouvrir le modèle 3D →')}</span></a>`; };
const html = `<!-- more-robots -->
        <div class="anat-home" id="more-robots">
          <h3>${tx('More robot families', 'Autres familles de robots')}</h3>
          <p>${tx('The other classic structures of robot arms, each with its 3D model, its joints, its kinematic diagram, its DH table and its models.', 'Les autres structures classiques de bras robotisés, chacune avec son modèle 3D, ses articulations, son schéma cinématique, son tableau DH et ses modèles.')}</p>
          <div class="anat-grid">${CARDS.map(card).join('')}</div>
        </div>
        <!-- /more-robots -->
`;
const file = path.join(root, 'index.html'); let h = fs.readFileSync(file, 'utf8');
h = h.replace(/ *<!-- more-robots -->[\s\S]*?<!-- \/more-robots -->\n/, '');
if (!h.includes('<!-- anatomy-home -->')) throw new Error('index.html: marker <!-- anatomy-home --> not found');
h = h.replace(/ *<!-- anatomy-home -->/, (m) => '        ' + html + m);
fs.writeFileSync(file, h);
const browser = await chromium.launch({ executablePath: process.env.CHROME || undefined });
const page = await (await browser.newContext()).newPage();
await page.goto(pathToFileURL(file).href); await page.waitForFunction(() => window.RA && RA.hash);
const pairs = [...REG.entries()];
const keys = await page.evaluate((en) => en.map((s) => { const d = document.createElement('div'); d.innerHTML = s; return RA.hash(RA.norm(d.innerHTML)); }), pairs.map((p) => p[0]));
await browser.close();
const dict = {}; pairs.forEach(([, fr], i) => { dict[keys[i]] = fr; });
const f = path.join(root, 'i18n', 'fr-index.js');
const s = fs.readFileSync(f, 'utf8').replace(/\n?\/\/ BEGIN more-robots[\s\S]*?\/\/ END more-robots\n?/, '\n');
fs.writeFileSync(f, s.trimEnd() + `\n// BEGIN more-robots (generated by tools/add-more-robots.mjs)\nRA.add(${JSON.stringify(dict, null, 1)});\n// END more-robots\n`);
console.log('more-robots: cards', CARDS.length, 'texts', pairs.length);
