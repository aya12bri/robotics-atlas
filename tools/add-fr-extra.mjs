// add-fr-extra.mjs — extra French texts for hand-written pages, from tools/fr-extra.mjs ({ 'page.html': [[English HTML, French HTML], …] }),
// added to i18n/fr-<page>.js in a "BEGIN extra … END extra" block (replaced on each run, the rest of the file is kept). Idempotent.
//   PLAYWRIGHT=… CHROME=… node tools/add-fr-extra.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const { chromium } = await import(process.env.PLAYWRIGHT || 'playwright-core');
const { EXTRA } = await import(pathToFileURL(path.join(root, 'tools', 'fr-extra.mjs')).href + '?t=' + Date.now());
const browser = await chromium.launch({ executablePath: process.env.CHROME || undefined });
const page = await (await browser.newContext()).newPage();
await page.goto(pathToFileURL(path.join(root, 'index.html')).href); await page.waitForFunction(() => window.RA && RA.hash);
for (const [file, pairs] of Object.entries(EXTRA)) {
  const keys = await page.evaluate((en) => en.map((s) => { const d = document.createElement('div'); d.innerHTML = s; return RA.hash(RA.norm(d.innerHTML)); }), pairs.map((p) => p[0]));
  const dict = {}; pairs.forEach(([, fr], i) => { dict[keys[i]] = fr; });
  const f = path.join(root, 'i18n', `fr-${file.replace(/\.html$/, '')}.js`);
  const s = fs.existsSync(f) ? fs.readFileSync(f, 'utf8').replace(/\n?\/\/ BEGIN extra[\s\S]*?\/\/ END extra\n?/, '\n') : `// Français — page ${file}.\n`;
  fs.writeFileSync(f, s.trimEnd() + `\n// BEGIN extra (generated by tools/add-fr-extra.mjs)\nRA.add(${JSON.stringify(dict, null, 1)});\n// END extra\n`);
  console.log(file, pairs.length);
}
await browser.close();
