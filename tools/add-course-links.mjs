// add-course-links.mjs — adds a link to the course "Wheeled mobile robots" on the two hand-written mobile-robot pages
// (mobile.html and wheels.html), with its French text. Idempotent.
//   node tools/add-course-links.mjs      (needs playwright-core and Chromium, like tools/build.mjs)
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const { chromium } = await import(process.env.PLAYWRIGHT || 'playwright-core');
const LINK = ['Take the course: wheeled mobile robots →', 'Suivre le cours : robots mobiles à roues →'];
const PAGES = [
  { file: 'wheels', before: '    <h2>5. Everything else about mobile robots</h2>',
    p: ['The words above are only the start. The course on wheeled mobile robots proves them with equations: the two constraints of every wheel type, the ICC of each drive, the degrees of mobility and steerability, and a controller that drives a robot to a goal.',
        'Les mots ci-dessus ne sont qu\'un début. Le cours sur les robots mobiles à roues les démontre avec des équations : les deux contraintes de chaque type de roue, le CIR de chaque motorisation, les degrés de mobilité et d\'orientabilité, et un contrôleur qui conduit un robot vers un but.'] },
  { file: 'mobile', before: '    <div class="robot">\n      <h2>Where is a mobile robot used?</h2>',
    p: ['Where does this model come from, and what about tricycles, cars and omnidirectional robots? The course on wheeled mobile robots derives it from the constraints of the wheels, step by step, with a simulator for each drive and a controller to try.',
        'D\'où vient ce modèle, et que dire des tricycles, des voitures et des robots omnidirectionnels ? Le cours sur les robots mobiles à roues le déduit des contraintes des roues, pas à pas, avec un simulateur pour chaque motorisation et un contrôleur à essayer.'] }
];
const browser = await chromium.launch({ executablePath: process.env.CHROME || undefined });
const page = await (await browser.newContext()).newPage();
for (const P of PAGES) {
  const file = path.join(root, P.file + '.html'); let h = fs.readFileSync(file, 'utf8');
  if (h.indexOf('href="learn-mobile.html"') < 0) {
    if (h.indexOf(P.before) < 0) throw new Error('anchor not found in ' + P.file);
    h = h.replace(P.before, `    <p>${P.p[0]}</p>\n    <p class="try"><a href="learn-mobile.html">${LINK[0]}</a></p>\n\n${P.before}`);
    fs.writeFileSync(file, h);
  }
  await page.goto(pathToFileURL(file).href); await page.waitForFunction(() => window.RA && RA.hash);
  const keys = await page.evaluate((en) => en.map((s) => { const d = document.createElement('div'); d.innerHTML = s; return RA.hash(RA.norm(d.innerHTML)); }), [P.p[0], LINK[0]]);
  const dict = { [keys[0]]: P.p[1], [keys[1]]: LINK[1] };
  const f = path.join(root, 'i18n', `fr-${P.file}.js`);
  const s = fs.readFileSync(f, 'utf8').replace(/\n?\/\/ BEGIN course-link[\s\S]*?\/\/ END course-link\n?/, '\n');
  fs.writeFileSync(f, s.trimEnd() + `\n// BEGIN course-link (generated by tools/add-course-links.mjs)\nRA.add(${JSON.stringify(dict, null, 1)});\n// END course-link\n`);
  console.log(P.file, 'ok');
}
await browser.close();
